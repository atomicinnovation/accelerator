// Usage: node tools/measure-fonts.js [--chrome PATH]
//
// Measures every character the vendored fonts cover, in headless Chrome, and
// writes lib/font-metrics.js: the advance width of each character in ems, per
// face. Layout runs without a browser, so this table is how it knows how wide
// a label will be drawn. Run it again whenever a vendored font changes.

const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { chromePath } = require('../lib/browser.js');

const KIT = path.resolve(__dirname, '..');
const FACES = {
  'sans-400': ['Kit Sans', 400, 'ibm-plex-sans-latin-400-normal.woff2'],
  'sans-600': ['Kit Sans', 600, 'ibm-plex-sans-latin-600-normal.woff2'],
  'mono-400': ['Kit Mono', 400, 'jetbrains-mono-latin-400-normal.woff2'],
  'mono-600': ['Kit Mono', 600, 'jetbrains-mono-latin-600-normal.woff2'],
};
function measuringPage() {
  const faces = Object.values(FACES).map(([family, weight, file]) => {
    const data = fs.readFileSync(path.join(KIT, 'vendor/fonts', file)).toString('base64');
    return `@font-face{font-family:"${family}";font-weight:${weight};src:url(data:font/woff2;base64,${data}) format("woff2")}`;
  }).join('');
  const measure = async faces => {
    const covered = [[0x20, 0x7e], [0xa1, 0xff], [0x2010, 0x2027], [0x2030, 0x203a]];
    const characters = covered.flatMap(([from, to]) => Array.from({ length: to - from + 1 }, (_, i) => String.fromCodePoint(from + i)));
    const context = document.createElement('canvas').getContext('2d');
    const table = {};
    for (const [name, [family, weight]] of Object.entries(faces)) {
      const font = `${weight} 100px "${family}"`;
      await document.fonts.load(font);
      if (!document.fonts.check(font)) throw new Error(`${name} did not load`);
      context.font = font;
      table[name] = Object.fromEntries(characters.map(c => [c, Math.round(context.measureText(c).width * 10) / 1000]));
    }
    return table;
  };
  return `<!doctype html><meta charset="utf-8"><style>${faces}</style><pre id="out"></pre><script>
    (${measure})(${JSON.stringify(FACES)}).then(table => { document.getElementById('out').textContent = JSON.stringify(table); },
      error => { document.getElementById('out').textContent = 'FAILED ' + error.message; });
  </script>`;
}

function compact(widths) {
  const counts = new Map();
  Object.values(widths).forEach(width => counts.set(width, (counts.get(width) || 0) + 1));
  const usual = [...counts].sort((a, b) => b[1] - a[1])[0][0];
  const others = Object.fromEntries(Object.entries(widths).filter(([, width]) => width !== usual));
  return { usual, others };
}

function main(argv) {
  const chrome = chromePath(argv.includes('--chrome') ? argv[argv.indexOf('--chrome') + 1] : undefined);
  if (!chrome) throw new Error('Chrome or Chromium is needed to measure the fonts; pass --chrome PATH');
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'diagram-kit-fonts-'));
  const page = path.join(dir, 'measure.html');
  fs.writeFileSync(page, measuringPage());
  const dom = execFileSync(chrome, ['--headless=new', '--disable-gpu', '--virtual-time-budget=10000', '--dump-dom', `file://${page}`], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 1 << 26 });
  const text = (dom.match(/<pre id="out">([\s\S]*?)<\/pre>/) || [])[1] || '';
  if (!text.startsWith('{')) throw new Error(`the fonts could not be measured: ${text || 'no output'}`);
  const unescaped = text.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
  const table = Object.fromEntries(Object.entries(JSON.parse(unescaped)).map(([face, widths]) => [face, compact(widths)]));
  const module = `// Generated by tools/measure-fonts.js from vendor/fonts. Do not edit.
(function (root) {
  'use strict';
  const FONT_METRICS = ${JSON.stringify(table)};
  if (typeof module === 'object' && module.exports) module.exports = { FONT_METRICS };
  else root.DiagramKit = Object.assign(root.DiagramKit || {}, { FONT_METRICS });
})(typeof window !== 'undefined' ? window : globalThis);
`;
  fs.writeFileSync(path.join(KIT, 'lib/font-metrics.js'), module);
  console.log(`wrote lib/font-metrics.js: ${Object.entries(table).map(([face, { others }]) => `${face} ${Object.keys(others).length + 1} widths`).join(', ')}`);
}

main(process.argv.slice(2));
